    // Forwards the system's push-notification registration result to the
    // Capacitor PushNotifications plugin. Purely additive — doesn't change
    // any existing behavior; only fires once push is actually requested.
    func application(_ application: UIApplication, didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        NotificationCenter.default.post(name: .capacitorDidRegisterForRemoteNotifications, object: deviceToken)
    }

    func application(_ application: UIApplication, didFailToRegisterForRemoteNotificationsWithError error: Error) {
        NotificationCenter.default.post(name: .capacitorDidFailToRegisterForRemoteNotifications, object: error)
    }

    // Lets a notification actually show its banner/sound/badge while the app
    // is open and in the foreground (iOS hides notifications by default
    // otherwise). Needed for the feature to be visibly real, not just wired
    // up in the background.
    func userNotificationCenter(_ center: UNUserNotificationCenter,
                                 willPresent notification: UNNotification,
                                 withCompletionHandler completionHandler: @escaping (UNNotificationPresentationOptions) -> Void) {
